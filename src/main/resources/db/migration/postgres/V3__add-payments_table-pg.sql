CREATE TYPE payment_method AS ENUM ('CREDIT_CARD', 'DEBIT_CARD', 'PIX', 'CASH', 'WITH_FINANCE_DEPT');

CREATE TABLE tb_payments
(
    id            BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    method        payment_method,
    amount        DECIMAL(10, 2),
    stay_id       BIGINT NOT NULL,
    creation_date DATE,

    CONSTRAINT tb_payments__stay FOREIGN KEY (stay_id) REFERENCES tb_stays (id)
);

CREATE TABLE daily_prices
(
    id                BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    one_guest_price   DECIMAL(6, 2) NOT NULL,
    two_guest_price   DECIMAL(6, 2) NOT NULL,
    three_guest_price DECIMAL(6, 2) NOT NULL,
    four_guest_price  DECIMAL(6, 2) NOT NULL
);

